// Helper functions
function getHostById(hostId) {
    return botHosts.find(host => host.id === hostId);
}

function getPodcastById(podcastId) {
    return podcasts.find(podcast => podcast.id === podcastId);
}

function getEpisodeById(episodeId) {
    return episodes.find(episode => episode.id === episodeId);
}

function getEpisodesByPodcast(podcastId) {
    return episodes.filter(episode => episode.podcastId === podcastId);
}

function getTrendingEpisodes(limit = 5) {
    return [...episodes].sort((a, b) => b.plays - a.plays).slice(0, limit);
}

function formatDate(dateString) {
    const date = new Date(dateString);
    const months = ['ינואר', 'פברואר', 'מרץ', 'אפריל', 'מאי', 'יוני', 'יולי', 'אוגוסט', 'ספטמבר', 'אוקטובר', 'נובמבר', 'דצמבר'];
    return `${date.getDate()} ב${months[date.getMonth()]} ${date.getFullYear()}`;
}
